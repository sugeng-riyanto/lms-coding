#!/usr/bin/env node
// pilot-env-render.mjs — render .env.pilot from inputs, no secrets hardcoded.
//
// Usage:
//   PILOT_REF=abcdefghijklmnopqrst PILOT_DOMAIN=pilot.example.org \
//   PILOT_PUBLISHABLE=sb_publishable_xxx PILOT_SERVICE_ROLE=eyJ... \
//   CERT_SIGNING_SECRET=<hex> \
//   node scripts/pilot-env-render.mjs > .env.pilot
//   node scripts/check-env.mjs .env.pilot
//
// Keys follow .env.example; flags default to the production posture (all OFF).
// Supabase CLI is not invoked; it is up to the operator to set the values from
// the dashboard. Output goes to stdout so the caller decides where the file
// lives (and keeps it out of git).

const req = (name) => {
  const v = process.env[name];
  if (!v) {
    console.error(
      `pilot-env-render: missing ${name} (set PILOT_REF, PILOT_DOMAIN, PILOT_PUBLISHABLE, PILOT_SERVICE_ROLE, CERT_SIGNING_SECRET)`,
    );
    process.exit(2);
  }
  return v;
};

const ref = req("PILOT_REF");
const domain = req("PILOT_DOMAIN");
const publishable = req("PILOT_PUBLISHABLE");
const serviceRole = req("PILOT_SERVICE_ROLE");
const certSecret = req("CERT_SIGNING_SECRET");

const out = `# Generated by scripts/pilot-env-render.mjs — pilot (staging, demo data). DO NOT COMMIT.
NEXT_PUBLIC_APP_URL=https://${domain}
NEXT_PUBLIC_SUPABASE_URL=https://${ref}.supabase.co
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}
SUPABASE_SECRET_KEY=${serviceRole}
CERTIFICATE_SIGNING_SECRET=${certSecret}
CSP_REPORT_ONLY=true
CSP_ALERT_THRESHOLD_PER_MIN=20
CSP_ALERT_WEBHOOK_URL=
ROBLOX_WEBHOOK_SECRET=
BLOCKCHAIN_ANCHOR_ENABLED=false
BLOCKCHAIN_PROVIDER=
BLOCKCHAIN_NETWORK=
BLOCKCHAIN_ALGORAND_RPC_URL=
BLOCKCHAIN_ALGORAND_API_KEY=
AI_FEEDBACK_ENABLED=false
AI_PROVIDER=
AI_PROVIDER_BASE_URL=
AI_PROVIDER_API_KEY=
CODE_RUNNER_ENABLED=false
CODE_RUNNER_PROVIDER=
CODE_RUNNER_BASE_URL=
CODE_RUNNER_API_KEY=
SUPABASE_ACCESS_TOKEN=
`;

process.stdout.write(out);
